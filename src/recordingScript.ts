import type { UsageEvent } from "./types.js";
import { recordingChecklist } from "./recordingChecklist.js";
import { recordingPack } from "./recordingPack.js";
import { outreachSnippet } from "./outreachSnippet.js";

export type RecordingScript = {
  version: "tokenpulse-recording-script-v1";
  ready: boolean;
  markdown: string;
  nextAction: string;
};

/** Linear, ready-to-read Markdown script for recording DEMO.md.
 * Visibility / operator convenience only. No policy or ledger change. */
export function recordingScript(events: UsageEvent[], opts?: { monthlyRequests?: number }): RecordingScript {
  const checklist = recordingChecklist(events);
  const pack = recordingPack(events, opts);
  const snip = outreachSnippet(events);

  const s = pack.summary;
  const lines: string[] = [
    "# Tokenpulse DEMO recording script",
    "",
    `**Status:** ${checklist.ready ? "READY" : "needs attention"}`,
    `**Next:** ${checklist.nextAction}`,
    "",
    "## Pre-flight",
    "",
    ...checklist.items.map((i) => `- [${i.done ? "x" : " "}] ${i.label} — ${i.detail}`),
    "",
    "## Key numbers (read from dashboard or this sheet)",
    "",
    `- Allowed calls: ${s.allowCount}`,
    `- Blocked calls: ${s.blockCount}`,
    `- Day span: ${s.daySpan}`,
    `- Policy ROI (avoided %): ${s.policyRoiPct.toFixed(1)}%`,
    `- Annual projected spend: $${s.annualProjectedUsd.toLocaleString(undefined, { maximumFractionDigits: 0 })}`,
    `- Annual estimated avoided: $${s.annualAvoidedUsd.toLocaleString(undefined, { maximumFractionDigits: 0 })}`,
    `- Scale-model monthly avoided: $${s.scaleMonthlyAvoidedUsd.toLocaleString(undefined, { maximumFractionDigits: 0 })}`,
    "",
    "## Spoken outline (read aloud while pointing at dashboard)",
    "",
    "1. Tokenpulse is a self-hosted OpenAI-compatible gateway. Clients set baseURL to us. We meter every token, attribute spend to team and app, and enforce budget and data policy *before* any provider call.",
    "",
    "2. On the dashboard you see spend by team, app, and model, plus blocked requests and estimated avoided cost. No raw prompts are stored.",
    "",
    `3. In this seeded ledger we have ${s.allowCount} allowed and ${s.blockCount} blocked calls across ${s.daySpan} days. Policy ROI is about ${s.policyRoiPct.toFixed(1)} percent avoided.`,
    "",
    `4. At the observed rate, annual projected spend is roughly $${s.annualProjectedUsd.toLocaleString(undefined, { maximumFractionDigits: 0 })} and estimated annual avoided is $${s.annualAvoidedUsd.toLocaleString(undefined, { maximumFractionDigits: 0 })}. The transparent scale model projects about $${s.scaleMonthlyAvoidedUsd.toLocaleString(undefined, { maximumFractionDigits: 0 })} monthly avoided at target volume.`,
    "",
    "5. The same numbers feed the FinOps and CISO export packs. CFOs get attribution and burn-rate; CISOs get blocked events and policy hits. Hash-chained ledger for audit.",
    "",
    "6. This is mock upstream. Live keys stay in the customer VPC. No secrets on camera.",
    "",
    "## CFO one-liner",
    "",
    pack.cfoLine || "(generate pack for CFO line)",
    "",
    "## Assumptions (state on camera)",
    "",
    ...(pack.assumptions.length ? pack.assumptions.map((a) => `- ${a}`) : ["- (none listed)"]),
    "",
    "## After recording",
    "",
    "- Personalize ≤10 emails from OUTREACH_DRAFTS.md",
    "- Insert the outreach snippet numbers",
    "",
    "### Outreach snippet",
    "",
    "```",
    snip.text || "(no snippet)",
    "```",
    "",
    "---",
    "Generated by Tokenpulse recordingScript. Visibility only. Do not paste secrets.",
  ];

  return {
    version: "tokenpulse-recording-script-v1",
    ready: checklist.ready,
    markdown: lines.join("\n"),
    nextAction: checklist.nextAction,
  };
}
