import type { AdminSummary } from "./admin.js";

/** Prometheus text exposition for operator scrapes. No secrets. */
export function metricsText(summary: AdminSummary): string {
  const lines: string[] = [
    "# HELP tokenpulse_calls_total Total ledger events (allow + block + note)",
    "# TYPE tokenpulse_calls_total counter",
    `tokenpulse_calls_total ${summary.calls}`,
    "# HELP tokenpulse_allowed_total Allowed requests",
    "# TYPE tokenpulse_allowed_total counter",
    `tokenpulse_allowed_total ${summary.allowed}`,
    "# HELP tokenpulse_blocked_total Blocked requests",
    "# TYPE tokenpulse_blocked_total counter",
    `tokenpulse_blocked_total ${summary.blocked}`,
    "# HELP tokenpulse_notes_total Operator notes",
    "# TYPE tokenpulse_notes_total counter",
    `tokenpulse_notes_total ${summary.notes}`,
    "# HELP tokenpulse_tokens_total Total tokens (prompt + completion)",
    "# TYPE tokenpulse_tokens_total counter",
    `tokenpulse_tokens_total ${summary.tokens}`,
    "# HELP tokenpulse_cost_usd_total Estimated cost in USD",
    "# TYPE tokenpulse_cost_usd_total counter",
    `tokenpulse_cost_usd_total ${summary.costUsd}`,
    "# HELP tokenpulse_alerts_count Current operator-visible warn count",
    "# TYPE tokenpulse_alerts_count gauge",
    `tokenpulse_alerts_count ${summary.alerts.count}`,
    "# HELP tokenpulse_discovery_unknown_cost_usd Estimated spend on models absent from the pricing catalog",
    "# TYPE tokenpulse_discovery_unknown_cost_usd gauge",
    `tokenpulse_discovery_unknown_cost_usd ${summary.discovery?.unknownCostUsd ?? 0}`,
    "# HELP tokenpulse_unattributed_cost_usd Estimated spend on default team or default app",
    "# TYPE tokenpulse_unattributed_cost_usd gauge",
    `tokenpulse_unattributed_cost_usd ${summary.unattributed?.unattributedCostUsd ?? 0}`,
    "# HELP tokenpulse_chain_ok 1 if the visible ledger chain verifies",
    "# TYPE tokenpulse_chain_ok gauge",
    `tokenpulse_chain_ok ${summary.chainOk ? 1 : 0}`,
    "# HELP tokenpulse_latency_avg_ms Average latency in milliseconds",
    "# TYPE tokenpulse_latency_avg_ms gauge",
    `tokenpulse_latency_avg_ms ${summary.latency?.avgMs ?? 0}`,
    "# HELP tokenpulse_latency_p95_ms 95th percentile latency in milliseconds",
    "# TYPE tokenpulse_latency_p95_ms gauge",
    `tokenpulse_latency_p95_ms ${summary.latency?.p95Ms ?? 0}`,
    "# HELP tokenpulse_upstream_success_rate_percent Success rate of requests that reached upstream (allow / (allow + upstream_error))",
    "# TYPE tokenpulse_upstream_success_rate_percent gauge",
    `tokenpulse_upstream_success_rate_percent ${summary.upstreamHealth?.successRate ?? 100}`,
    "# HELP tokenpulse_upstream_failures_total Blocks caused by upstream_error",
    "# TYPE tokenpulse_upstream_failures_total counter",
    `tokenpulse_upstream_failures_total ${summary.upstreamHealth?.failures ?? 0}`,
    "# HELP tokenpulse_burn_exhaust_warn_count Daily caps projected to exhaust by end of UTC day",
    "# TYPE tokenpulse_burn_exhaust_warn_count gauge",
    `tokenpulse_burn_exhaust_warn_count ${summary.burnRate?.exhaustWarnCount ?? 0}`,
    "# HELP tokenpulse_burn_monthly_exhaust_warn_count Monthly caps projected to exhaust by end of UTC month",
    "# TYPE tokenpulse_burn_monthly_exhaust_warn_count gauge",
    `tokenpulse_burn_monthly_exhaust_warn_count ${summary.burnRate?.monthlyExhaustWarnCount ?? 0}`,
    "# HELP tokenpulse_block_unique_policies Unique policy ids observed on block events",
    "# TYPE tokenpulse_block_unique_policies gauge",
    `tokenpulse_block_unique_policies ${summary.blockReasons?.uniquePolicies ?? 0}`,
    "# HELP tokenpulse_model_unique_models Unique client model ids with allowed spend",
    "# TYPE tokenpulse_model_unique_models gauge",
    `tokenpulse_model_unique_models ${summary.modelSpend?.uniqueModels ?? 0}`,
    "# HELP tokenpulse_team_unique_teams Unique team ids with allowed spend",
    "# TYPE tokenpulse_team_unique_teams gauge",
    `tokenpulse_team_unique_teams ${summary.teamSpend?.uniqueTeams ?? 0}`,
    "# HELP tokenpulse_high_cost_top_usd Highest single allowed request cost in the window",
    "# TYPE tokenpulse_high_cost_top_usd gauge",
    `tokenpulse_high_cost_top_usd ${summary.highCost?.rows?.[0]?.estimatedCostUsd ?? 0}`,
    "# HELP tokenpulse_high_cost_count Number of high-cost rows returned",
    "# TYPE tokenpulse_high_cost_count gauge",
    `tokenpulse_high_cost_count ${summary.highCost?.rows?.length ?? 0}`,
    "# HELP tokenpulse_app_unique_apps Unique app ids with allowed spend",
    "# TYPE tokenpulse_app_unique_apps gauge",
    `tokenpulse_app_unique_apps ${summary.appSpend?.uniqueApps ?? 0}`,

  ];
  return lines.join("\n") + "\n";
}
