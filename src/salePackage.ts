import type { UsageEvent } from "./types.js";
import { recordingChecklist } from "./recordingChecklist.js";
import { recordingScript } from "./recordingScript.js";
import { outreachSnippet } from "./outreachSnippet.js";
import { outreachDraft } from "./outreachDraft.js";
import { saleReadyStatus } from "./saleReady.js";

export type SalePackage = {
  version: "tokenpulse-sale-package-v1";
  ready: boolean;
  markdown: string;
  nextAction: string;
};

const BUYERS = ["palo-alto", "cisco", "crowdstrike", "doit", "default"] as const;

/** Single Markdown pack for recording DEMO.md then sending outreach.
 * Includes full drafts for all key buyers. Visibility / operator convenience only.
 * No policy or ledger change. */
export function salePackage(events: UsageEvent[]): SalePackage {
  const ready = saleReadyStatus(events);
  const checklist = recordingChecklist(events);
  const script = recordingScript(events);
  const snip = outreachSnippet(events);

  const draftSections: string[] = [];
  for (const buyer of BUYERS) {
    const draft = outreachDraft(events, buyer);
    const title = buyer === "default" ? "Default / general" : buyer;
    draftSections.push(
      `## Outreach draft (${title})`,
      "",
      draft.subject ? `Subject: ${draft.subject}` : "",
      "",
      draft.body || "(no draft)",
      "",
    );
  }

  const lines: string[] = [
    "# Tokenpulse Sale Package",
    "",
    `**Status:** ${ready.ready ? "SALE READY" : "Not ready"}`,
    `**Next:** ${ready.nextAction}`,
    `**Drafts ready:** ${ready.buyerDraftsReady}`,
    "",
    "## Sale readiness",
    "",
    ...ready.items.map((i) => `- [${i.done ? "x" : " "}] ${i.label} — ${i.detail}`),
    "",
    "## Recording checklist",
    "",
    ...checklist.items.map((i) => `- [${i.done ? "x" : " "}] ${i.label} — ${i.detail}`),
    "",
    "## Recording script",
    "",
    script.markdown,
    "",
    "## Outreach snippet",
    "",
    snip.body || "(no snippet)",
    "",
    ...draftSections,
    "---",
    "Generated by Tokenpulse. Fill {{Name}} / placeholders. Do not paste secrets. Recording remains an operator step. Use after DEMO.md recording.",
  ];

  return {
    version: "tokenpulse-sale-package-v1",
    ready: ready.ready,
    markdown: lines.filter(Boolean).join("\n"),
    nextAction: ready.nextAction,
  };
}
